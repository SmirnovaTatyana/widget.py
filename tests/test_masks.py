import pytest
from src.masks import get_mask_card_number, get_mask_account


@pytest.mark.parametrize(
    "card_number, expected",
    [
        # Корректные номера карт
        ("1234567890123456", "1234 56** **** 3456"),  # Стандартный номер карты
        ("9876543210987654", "9876 54** **** 7654"),  # Другой стандартный номер
        ("0000000000000000", "0000 00** **** 0000"),  # Номер из нулей

        # Граничные случаи
        ("123456789012345", "Некорректный номер карты"),  # Менее 16 цифр
        ("12345678901234567", "Некорректный номер карты"),  # Более 16 цифр

        # Некорректные номера карт
        ("1234-5678-9012-3456", "Некорректный номер карты"),  # С дефисами
        ("abcd123456789012", "Некорректный номер карты"),  # С буквами
        ("", "Некорректный номер карты"),  # Пустая строка
    ]
)
def test_get_mask_card_number(card_number, expected):
    """Тестирование функции get_mask_card_number."""
    assert get_mask_card_number(card_number) == expected


@pytest.mark.parametrize(
    "account_number, expected",
    [
        # Корректные номера счетов
        ("12345678901234567890", "**7890"),  # Исправленный ожидаемый результат
        ("00000000000000000000", "**0000"),  # Номер из нулей
        ("98765432109876543210", "**3210"),  # Другой стандартный номер

        # Граничные случаи
        ("1234", "**1234"),  # Минимальная длина (4 цифры)
        ("", "Некорректный номер счета"),  # Пустая строка

        # Некорректные номера счетов
        ("1234-abcd-5678", "Некорректный номер счета"),  # С буквами
        ("1234567890abcdef", "Некорректный номер счета"),  # С буквами
    ]
)
def test_get_mask_account(account_number, expected):
    """Тестирование функции get_mask_account."""
    assert get_mask_account(account_number) == expected